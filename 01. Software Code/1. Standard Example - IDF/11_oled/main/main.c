#include "driver/gpio.h"
#include "led.h"
#include "iic.h"
#include "xl9555.h"
#include "oled.h"

i2c_obj_t i2c0_master;
i2c_obj_t i2c1_master;

/**
 * @brief       Program entry
 * @param       none
 * @retval      none
 */
void app_main(void)
{
    uint8_t t = 0;

    led_init();                             /* initializationLED */
    i2c0_master = iic_init(I2C_NUM_0);      /* initializationIIC0 */
    i2c1_master = iic_init(I2C_NUM_1);      /* initializationIIC1 */
    xl9555_init(i2c0_master);               /* Initialize XL9555 */
    oled_init(i2c1_master);                 /* initializationOLED */

    oled_show_string(0, 0, "ALIENTEK", 24);
    oled_show_string(0, 24, "0.96' OLED TEST", 16);
    oled_show_string(0, 40, "ATOM 2023/8/26", 12);
    oled_show_string(0, 52, "ASCII:", 12);
    oled_show_string(64, 52, "CODE:", 12);
    oled_refresh_gram();                    /* Update display to OLED */
    
    t = ' ';
    while(1)
    {
        oled_show_char(36, 52, t, 12, 1);   /* Show ASCII characters */
        oled_show_num(94, 52, t, 3, 12);    /* showASCIICharacter code value */
        oled_refresh_gram();                /* Update display to OLED */
        t++;

        if (t > '~')
        {
            t = ' ';
        }

        vTaskDelay(500);
        LED_TOGGLE();                       /* LED flashing */
    }
}
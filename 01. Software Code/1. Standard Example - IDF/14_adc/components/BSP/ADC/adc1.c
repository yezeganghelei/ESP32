#include "adc1.h"

/**
 * @brief       initializationADC
 * @param       none
 * @retval      none
 */
void adc_init(void)
{
    adc_digi_pattern_config_t adc1_digi_pattern_config;         /* ADC1 configuration handle */
    adc_digi_configuration_t adc1_init_config;                  /* ADC1initializationHandle */
    
    /* Configure ADC1 */
    adc1_digi_pattern_config.atten = ADC_ATTEN_DB_11;           /* Configure the ADC attenuation level */
    adc1_digi_pattern_config.channel = ADC_ADCX_CHY;            /* ConfigurationADCaisle */
    adc1_digi_pattern_config.unit = ADC_UNIT_1;                 /* ConfigurationADCunit */
    adc1_digi_pattern_config.bit_width = ADC_BITWIDTH_12;       /* Configure the ADC bit width */
    adc1_init_config.adc_pattern = &adc1_digi_pattern_config;   /* Configure each ADC parameter to be used */
    adc_digi_controller_configure(&adc1_init_config);           /* Configure ADC1 */
}

/**
 * @brief       GetADCThe result after conversion and mean filtering
 * @param       ch      : Channel number, 0~9
 * @param       times   : Number of acquisitions
 * @retval      aislechoftimesAverage of the results of the conversion
 */
uint32_t adc_get_result_average(uint32_t ch, uint32_t times)
{
    uint32_t temp_val = 0;
    uint8_t t;

    for (t = 0; t < times; t++) /* Get times data */
    {
        temp_val += adc1_get_raw(ch);
        vTaskDelay(5);
    }

    return temp_val / times;    /* Return to the average */
}
#include "touch.h"

_m_tp_dev tp_dev =
{{
    tp_init,
    0,
    0,
    0,
    0,
    0,
}};

/**
 * @brief       touchscreeninitialization
 * @param       none
 * @retval      0,touchscreenInitialization successfully
 *              1,touchscreenHave a problem
 */
uint8_t tp_init(void)
{
    tp_dev.touchtype = 0;                                   /* Default settings(Resistor screen & Vertical screen) */
    tp_dev.touchtype |= ltdcdev.dir & 0X01;                 /* according toLCDDetermine whether it is a horizontal screen orVertical screen */

    if (ltdcdev.id == 0X4342 || ltdcdev.id == 0X4384)       /* capacitancetouchscreen,4.3Cunscreen */
    {
        gt9xxx_init();
        tp_dev.scan = gt9xxx_scan;                          /* Scan function points toGTtouchscreen */
        tp_dev.touchtype |= 0X80;                           /* Capacitor screen */
        return 0;
    }

    return 1;
}
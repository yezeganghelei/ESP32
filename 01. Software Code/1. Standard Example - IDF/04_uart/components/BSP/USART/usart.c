#include "usart.h"

/**
 * @brief       Initialize the serial port
 * @param       baudrate: Baud rate, Set the baud rate value according to your needs
 * @note        Notice: The correct clock source must be set, Otherwise, the baud rate of the serial port will be set abnormally.
 * @retval      none
 */
void usart_init(uint32_t baudrate)
{
    uart_config_t uart_config;                          /* Serial portConfigurationHandle */

    uart_config.baud_rate = baudrate;                   /* Baud rate */
    uart_config.data_bits = UART_DATA_8_BITS;           /* Word length is 8-bit data format */
    uart_config.parity = UART_PARITY_DISABLE;           /* noneParity bit */
    uart_config.stop_bits = UART_STOP_BITS_1;           /* A stop bit */
    uart_config.flow_ctrl = UART_HW_FLOWCTRL_DISABLE;   /* noneHardware control flow */
    uart_config.source_clk = UART_SCLK_APB;             /* Configure the clock source */
    uart_config.rx_flow_ctrl_thresh = 122;              /* Hardware control flow threshold */
    uart_param_config(USART_UX, &uart_config);          /* Configurationuartport */

    /* ConfigurationuartPin */
    uart_set_pin(USART_UX, USART_TX_GPIO_PIN, USART_RX_GPIO_PIN, UART_PIN_NO_CHANGE, UART_PIN_NO_CHANGE);

    /* Install the serial port driver */
    uart_driver_install(USART_UX, RX_BUF_SIZE * 2, RX_BUF_SIZE * 2, 20, NULL, 0);
}
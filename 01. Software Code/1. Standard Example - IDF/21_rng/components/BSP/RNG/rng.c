#include "rng.h"

/**
 * @brief       Get random numbers
 * @param       none
 * @retval      Random number obtained(32bit)
 */
uint32_t rng_get_random_num(void)
{
    uint32_t randomnum;
    
    randomnum = esp_random();
    
    return randomnum;
}

/**
 * @brief       Get random numbers in a range
 * @param       min,max: Minimum,Maximum value.
 * @retval      The random number obtained(rval),satisfy:min<=rval<=max
 */
int rng_get_random_range(int min, int max)
{ 
    uint32_t randomnum;
    
    randomnum = esp_random();
    
    return randomnum % (max - min + 1) + min;
}
#ifndef __LED_H_
#define __LED_H_

#include "driver/gpio.h"

/* Pin definition */
#define LED_GPIO_PIN    GPIO_NUM_1  /* LEDConnectedGPIOport */

/* Level status of pin output */
enum GPIO_OUTPUT_STATE
{
    PIN_RESET,
    PIN_SET
};

/* LED port definition */
#define LED(x)          do { x ?                                      \
                             gpio_set_level(LED_GPIO_PIN, PIN_SET) :  \
                             gpio_set_level(LED_GPIO_PIN, PIN_RESET); \
                        } while(0)  /* LEDFlip */

/* LEDNegative definition */
#define LED_TOGGLE()    do { gpio_set_level(LED_GPIO_PIN, !gpio_get_level(LED_GPIO_PIN)); } while(0)  /* LEDFlip */

/* Function declaration*/
void led_init(void);    /* Initialize LED */

#endif
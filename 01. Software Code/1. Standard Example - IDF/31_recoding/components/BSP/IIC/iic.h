#ifndef __IIC_H
#define __IIC_H

#include "driver/gpio.h"
#include "driver/i2c.h"
#include "esp_err.h"

/* IICcontrol block */
typedef struct _i2c_obj_t {
    i2c_port_t port;
    gpio_num_t scl;
    gpio_num_t sda;
    esp_err_t init_flag;
} i2c_obj_t;

/* Read and write dataStructure */
typedef struct _i2c_buf_t {
    size_t len;
    uint8_t *buf;
} i2c_buf_t;

extern i2c_obj_t iic_master[I2C_NUM_MAX];

/* readWrite a logoBit */
#define I2C_FLAG_READ                   (0x01)                                                          /* Read the logo */
#define I2C_FLAG_STOP                   (0x02)                                                          /* stop sign */
#define I2C_FLAG_WRITE                  (0x04)                                                          /* Write a logo */

/* Pin and related parameter definitions */
#define IIC0_SDA_GPIO_PIN               GPIO_NUM_41                                                     /* IIC0_SDA pin */
#define IIC0_SCL_GPIO_PIN               GPIO_NUM_42                                                     /* IIC0_SCL pin */
#define IIC1_SDA_GPIO_PIN               GPIO_NUM_5                                                      /* IIC1_SDA pin */
#define IIC1_SCL_GPIO_PIN               GPIO_NUM_4                                                      /* IIC1_SCL pin */
#define IIC_FREQ                        400000                                                          /* IICCommunication frequency */
#define I2C_MASTER_TX_BUF_DISABLE       0                                                               /* I2CThe host does not require a buffer */
#define I2C_MASTER_RX_BUF_DISABLE       0                                                               /* I2CThe host does not require a buffer */
#define ACK_CHECK_EN                    0x1                                                             /* I2C masterWillslaveexamineACK */

/* Function declaration */
i2c_obj_t iic_init(uint8_t iic_port);                                                                   /* initializationIIC */
esp_err_t i2c_transfer(i2c_obj_t *self, uint16_t addr, size_t n, i2c_buf_t *bufs, unsigned int flags);  /* IIC reads and writes data */

#endif
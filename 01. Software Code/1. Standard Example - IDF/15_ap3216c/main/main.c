#include "freertos/FreeRTOS.h"
#include "freertos/task.h"
#include "nvs_flash.h"
#include "led.h"
#include "lcd.h"
#include "spi.h"
#include "iic.h"
#include "xl9555.h"
#include "ap3216c.h"

i2c_obj_t i2c0_master;

/**
 * @brief       Program entry
 * @param       none
 * @retval      none
 */
void app_main(void)
{
    uint16_t ir, als, ps;
    esp_err_t ret;
    
    ret = nvs_flash_init();                             /* Initialize NVS */

    if (ret == ESP_ERR_NVS_NO_FREE_PAGES || ret == ESP_ERR_NVS_NEW_VERSION_FOUND)
    {
        ESP_ERROR_CHECK(nvs_flash_erase());
        ret = nvs_flash_init();
    }

    led_init();                                         /* initializationLED */
    i2c0_master = iic_init(I2C_NUM_0);                  /* initializationIIC0 */
    spi2_init();                                        /* Initialize SPI2 */
    xl9555_init(i2c0_master);                           /* Initialize XL9555 */
    lcd_init();                                         /* Initialize LCD */
    ap3216c_init(i2c0_master);                          /* initializationAP3216C */

    lcd_show_string(10, 50, 200, 16, 16, "ESP32", RED);
    lcd_show_string(10, 70, 200, 16, 16, "AP3216C TEST", RED);
    lcd_show_string(10, 90, 200, 16, 16, "ATOM@ALIENTEK", RED);

    lcd_show_string(10, 130, 200, 16, 16, "AP3216C Ready!", RED);
    lcd_show_string(10, 150, 200, 16, 16, "IR :", RED);
    lcd_show_string(10, 170, 200, 16, 16, "PS :", RED);
    lcd_show_string(10, 190, 200, 16, 16, "ALS:", RED);

    while(1)
    {
        ap3216c_read_data(&ir, &ps, &als);              /* Readdata  */
        lcd_show_num(10 + 40, 150, ir, 5, 16, BLUE);    /* showIRdata */
        lcd_show_num(10 + 40, 170, ps, 5, 16, BLUE);    /* showPSdata */
        lcd_show_num(10 + 40, 190, als, 5, 16, BLUE);   /* showALSdata  */

        LED_TOGGLE();                                   /* Prompt the system is running */
        vTaskDelay(200);
    }
}
#ifndef _I2S_H
#define _I2S_H

#include <stdio.h>
#include <string.h>
#include "sdkconfig.h"
#include "driver/gpio.h"
#include "driver/i2s.h"
#include "esp_err.h"
#include "esp_log.h"
#include "es8388.h"
#include "driver/i2s_std.h"
#include "driver/i2s_pdm.h"

#define I2S_NUM                 (I2S_NUM_0)                 /* I2S port */
#define I2S_BCK_IO              (GPIO_NUM_46)               /* Set the serial clock pin，ES8388_SCLK */
#define I2S_WS_IO               (GPIO_NUM_9)                /* Set the clock pins of left and right channels，ES8388_LRCK */
#define I2S_DO_IO               (GPIO_NUM_10)               /* ES8388_SDOUT */
#define I2S_DI_IO               (GPIO_NUM_14)               /* ES8388_SDIN */
#define IS2_MCLK_IO             (GPIO_NUM_3)                /* ES8388_MCLK */
#define SAMPLE_RATE             (44100)                     /* Sampling rate */

/* Declare functions */
esp_err_t i2s_init(void);                                           /* I2Sinitialization */
void i2s_trx_start(void);                                           /* start upI2S */
void i2s_trx_stop(void);                                            /* stopI2S */
void i2s_deinit(void);                                              /* Uninstall I2S */
void i2s_set_samplerate_bits_sample(int samplerate,int bits_sample);/* Set the sampling rate and bit width */
size_t i2s_tx_write(uint8_t *buffer, uint32_t frame_size);          /* write data */
size_t i2s_rx_read(uint8_t *buffer, uint32_t frame_size);           /* Read data */

#endif